import test from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

test('HTTP session APIs persist state, reject stale writes and protect mutations', async t => {
  const directory=await mkdtemp(join(tmpdir(),'pitlane-http-'));
  let child;
  const start=()=>new Promise((resolve,reject)=>{
    child=spawn(process.execPath,['server.mjs'],{cwd:process.cwd(),windowsHide:true,env:{...process.env,ROOM_DATA_DIR:directory,ROOM_PORT:'0',ROOM_SKIP_CLI_CHECKS:'1'},stdio:['ignore','pipe','pipe']});
    let errors='',output='';const timer=setTimeout(()=>reject(new Error('Server timeout: '+errors)),10000);
    child.stderr.on('data',data=>errors+=data);
    child.stdout.on('data',data=>{output+=data;const match=output.match(/ready: (http:\/\/127.0.0.1:\d+)/);if(match){clearTimeout(timer);resolve(match[1]);}});
    child.once('error',reject);child.once('exit',code=>{clearTimeout(timer);if(!output.includes('ready:'))reject(new Error('Server exited '+code+': '+errors));});
  });
  const stop=async()=>{if(!child || child.exitCode!==null)return;const done=new Promise(resolve=>child.once('exit',resolve));child.kill();await done;};
  t.after(async()=>{await stop();assert.ok(directory.startsWith(join(tmpdir(),'pitlane-http-')));await rm(directory,{recursive:true,force:true});});
  let base=await start();
  const redirect=await fetch(base+'/',{redirect:'manual'});
  assert.equal(redirect.status,302);assert.equal(redirect.headers.get('location'),'http://127.0.0.1:4317/');
  assert.equal((await fetch(base+'/index.html',{redirect:'manual'})).status,302);
  assert.equal((await fetch(base+'/app.js')).status,404);
  assert.equal((await fetch(base+'/style.css')).status,404);
  let bootstrap=await (await fetch(base+'/api/bootstrap')).json();
  const request=async(path,input,method='POST',sessionId)=>{
    const res=await fetch(base+path,{method,headers:{'Content-Type':'application/json','X-Room-Token':bootstrap.token,...(sessionId?{'X-Room-Session':sessionId}:{})},...(method!=='GET'&&method!=='DELETE'?{body:JSON.stringify(input)}:{})});
    return {status:res.status,data:await res.json()};
  };
  assert.equal((await fetch(base+'/api/sessions/new',{method:'POST'})).status,403);
  assert.equal((await fetch(base+'/api/linked-apps/chats?provider=codex')).status,403);
  assert.equal((await fetch(base+'/api/projects/linked-apps',{method:'POST'})).status,403);
  assert.equal((await request('/api/linked-apps/chats?provider=unknown',null,'GET')).status,400);
  assert.equal((await request('/api/projects/linked-apps',{projectId:'missing',links:{claude:{id:'native-chat'}}})).status,400);
  assert.equal((await request('/api/projects/linked-apps',{projectId:'missing',links:{codex:{id:'../outside'}}})).status,400);
  const blocked=await fetch(base+'/api/bootstrap',{headers:{Origin:'https://untrusted.example'}});assert.equal(blocked.status,403);
  assert.equal(bootstrap.state.language,'en');
  assert.equal((await fetch(base+'/api/language',{method:'POST'})).status,403);
  assert.equal((await request('/api/language',{language:'fr'})).status,400);
  assert.equal((await request('/api/language',{language:'id'})).data.state.language,'id');
  let result=await request('/api/sessions/new',{title:'Endpoint Test',soulContent:'# HTTP Project'});
  assert.equal(result.status,200);const id=result.data.state.sessionId;
  assert.equal(result.data.state.messages.length,0);
  const eventsController=new AbortController();
  const events=await fetch(base+'/api/events?token='+bootstrap.token,{signal:AbortSignal.any([eventsController.signal,AbortSignal.timeout(4000)])});
  assert.match(events.headers.get('content-type'),/text\/event-stream/);
  const reader=events.body.getReader();
  const initial=new TextDecoder().decode((await reader.read()).value);
  assert.match(initial,new RegExp(id));
  await request('/api/profile',{displayName:'HTTP User'},'POST',id);
  const update=new TextDecoder().decode((await reader.read()).value);
  assert.match(update,/HTTP User/);
  eventsController.abort();await reader.cancel().catch(()=>{});
  result=await request('/api/soul',{content:'# Stale edit',revision:1},'POST','session-default');
  assert.equal(result.status,400);assert.match(result.data.error,/Sesi aktif berubah/);
  result=await request('/api/project-memory',{content:'# HTTP Saved',revision:1},'POST',id);assert.equal(result.status,200);
  result=await request('/api/sessions/rename',{sessionId:id,title:'Renamed'});assert.equal(result.status,200);
  result=await request('/api/sessions/switch',{sessionId:'session-default'});assert.equal(result.status,200);
  assert.doesNotMatch(result.data.state.projectMemory.content,/HTTP Saved/);
  await stop();base=await start();bootstrap=await (await fetch(base+'/api/bootstrap')).json();
  assert.equal(bootstrap.state.language,'id');
  result=await request('/api/sessions/switch',{sessionId:id});assert.equal(result.status,200);
  assert.match(result.data.state.projectMemory.content,/HTTP Saved/);
  assert.equal(result.data.state.sessions.find(s=>s.id===id).title,'Renamed');
  result=await request('/api/sessions/'+id,null,'DELETE');assert.equal(result.status,200);
  result=await request('/api/sessions/session-default',null,'DELETE');assert.equal(result.status,200);
  const replacementId=result.data.state.sessionId;
  assert.notEqual(replacementId,'session-default');assert.equal(result.data.state.messages.length,0);assert.equal(result.data.state.sessions.length,1);
  result=await request('/api/projects/new',{name:'API Project',agentIds:['codex']});assert.equal(result.status,200);
  const projectId=result.data.state.projects[0].id,projectSession=result.data.state.sessionId;
  assert.equal((await request('/api/projects/linked-apps',{projectId,links:{}})).status,200);
  result=await request('/api/sessions/new',{title:'Sibling',projectId});assert.equal(result.status,200);
  assert.equal(result.data.state.sessions.filter(s=>s.projectId===projectId).length,2);
  result=await request('/api/projects/move',{sessionId:replacementId,projectId});assert.equal(result.status,200);
  assert.equal(result.data.state.sessions.find(s=>s.id===replacementId).projectId,projectId);
  result=await request('/api/projects/session-agents',{sessionId:projectSession,agentIds:['antigravity']});assert.equal(result.status,400);
  result=await request('/api/send',{text:'Agent excluded',mode:'antigravity'});assert.equal(result.status,400);
  await stop();base=await start();bootstrap=await(await fetch(base+'/api/bootstrap')).json();
  assert.equal(bootstrap.state.projects[0].id,projectId);
  assert.equal(bootstrap.state.sessions.filter(s=>s.projectId===projectId).length,3);
  const shared=bootstrap.state.projectMemory;
  result=await request('/api/project-memory',{content:'# Shared Project Concept',revision:shared.revision,scopeId:'wrong-scope'});assert.equal(result.status,400);
  result=await request('/api/project-memory',{content:'# Shared Project Concept',revision:shared.revision,scopeId:shared.scopeId});assert.equal(result.status,200);
  result=await request('/api/soul',{content:'Use English and be concise.',revision:bootstrap.state.brain.soul.revision});assert.equal(result.status,200);
  assert.equal(result.data.brain.soul.content,'Use English and be concise.');
  result=await request('/api/sessions/switch',{sessionId:projectSession});assert.equal(result.status,200);
  assert.match(result.data.state.projectMemory.content,/Shared Project Concept/);
  assert.equal(result.data.state.brain.soul.content,'Use English and be concise.');

  result=await request('/api/projects/delete',{projectId,confirmation:'delete'});assert.equal(result.status,400);
  result=await request('/api/projects/delete',{projectId,confirmation:'DELETE'});assert.equal(result.status,200);
  assert.equal(result.data.state.projects.length,0);
  assert.equal(result.data.state.sessions.length,3);
  assert.ok(result.data.state.sessions.every(session=>!session.projectId));
  result=await request('/api/projects/delete',{projectId,confirmation:'DELETE'});assert.equal(result.status,400);


  const {default:sharp}=await import('sharp');
  const photo='data:image/jpeg;base64,'+(await sharp({create:{width:8,height:8,channels:3,background:'#2563eb'}}).jpeg().toBuffer()).toString('base64');
  const profile={provider:'codex',name:'Race Engineer',role:'Architect',bio:'Review architecture decisions.',avatar:photo};
  const before=await(await fetch(base+'/api/bootstrap')).json();
  result=await request('/api/agents/profile',profile);assert.equal(result.status,200);
  const agent=result.data.state.agents.find(a=>a.id==='codex');
  assert.equal(agent.name,profile.name);assert.equal(agent.avatar,photo);assert.equal(agent.bio,profile.bio);
  assert.deepEqual(result.data.state.brain.selections,before.state.brain.selections);
  result=await request('/api/agents/profile',{...profile,selection:{model:'custom-test-model',effort:'low',custom:true}});assert.equal(result.status,200);
  assert.equal(result.data.state.brain.selections.codex.model,'custom-test-model');
  assert.deepEqual(result.data.state.brain.selections.antigravity,before.state.brain.selections.antigravity);
  result=await request('/api/agents/profile',{...profile,name:'Should not save',selection:{model:'invalid model id',effort:'low',custom:true}});assert.equal(result.status,400);
  assert.equal((await request('/api/agents/profile',{...profile,provider:'unknown'})).status,400);
  assert.equal((await request('/api/agents/profile',{...profile,avatar:'https://example.com/file'})).status,400);
  assert.equal((await request('/api/agents/profile',{...profile,name:''})).status,400);
  await stop();base=await start();bootstrap=await(await fetch(base+'/api/bootstrap')).json();
  assert.equal(bootstrap.state.agents.find(a=>a.id==='codex').avatar,photo);
  assert.equal(bootstrap.state.agents.find(a=>a.id==='codex').name,profile.name);

});
