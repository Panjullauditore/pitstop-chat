import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm} from 'node:fs/promises';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {SessionStore} from '../sessions.mjs';

test('completed projects retain their sessions, memories and participants and can be reactivated after restart',async t=>{
  const directory=await mkdtemp(join(tmpdir(),'pitstop-project-status-'));
  const options={directory,seed:'# Project',agents:{codex:{id:'codex',installed:true}},runner:async()=>''};
  const store=new SessionStore(options);await store.load();
  t.after(async()=>{for(const room of store.rooms.values())await room.save();await store.queue;assert.ok(directory.startsWith(join(tmpdir(),'pitstop-project-status-')));await rm(directory,{recursive:true,force:true});});
  await store.createProject({name:'Garage Town',agentIds:['codex']});
  const projectId=store.projects[0].id,sessionId=store.activeId,memory=store.memorySnapshot(sessionId);
  assert.equal(store.snapshot().activeProjectId,projectId);
  await store.create({title:'Outside project'});
  assert.equal(store.snapshot().activeProjectId,projectId);
  await store.switch(sessionId);
  await store.setProjectStatus({projectId,status:'completed'});
  assert.equal(store.snapshot().activeProjectId,null);
  assert.equal(store.projects[0].status,'completed');assert.ok(store.projects[0].completedAt);
  assert.equal(store.activeId,sessionId);assert.equal(store.entries.find(s=>s.id===sessionId).projectId,projectId);
  assert.deepEqual(store.memorySnapshot(sessionId),memory);assert.deepEqual(store.projects[0].agentIds,['codex']);
  const restored=new SessionStore(options);await restored.load();
  assert.equal(restored.projects[0].status,'completed');
  assert.equal(restored.snapshot().activeProjectId,null);
  await restored.openProject(projectId);assert.equal(restored.snapshot().activeProjectId,null);
  await restored.setProjectStatus({projectId,status:'active'});await restored.openProject(projectId);
  assert.equal(restored.projects[0].status,'active');assert.equal(restored.projects[0].completedAt,undefined);
  assert.equal(restored.activeId,sessionId);
  assert.equal(restored.snapshot().activeProjectId,projectId);
  await assert.rejects(restored.setProjectStatus({projectId,status:'deleted'}),/tidak valid/);
  await assert.rejects(restored.setProjectStatus({projectId:'missing',status:'completed'}),/tidak ditemukan/);
  restored.projects[0].pendingDecision={id:'decision',question:'Waiting for GM'};
  await assert.rejects(restored.setProjectStatus({projectId,status:'completed'}),/General Manager/);
  delete restored.projects[0].pendingDecision;restored.room.run={id:'running'};
  await assert.rejects(restored.setProjectStatus({projectId,status:'completed'}),/Tunggu diskusi/);restored.room.run=null;
  for(const room of restored.rooms.values())await room.save();await restored.queue;
});
